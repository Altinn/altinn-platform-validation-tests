import { group } from "k6";

import { SystemRegisterClient } from "../../../../clients/authentication/v2/index.js";
import { RegisterSystemRequestBuilder } from "../../../../clients/authentication/v2/system-register.builders.js";
import { EnterpriseTokenBuilder, EnterpriseTokenGenerator, MaskinportenAccessTokenGenerator, MaskinportenTokenBuilder, uuidv4 } from "../../../../common-imports.js";
import { requireEnv } from "../../../../helpers.js";
import { AltinnScopes, CreateScopeString } from "../../../../scopes.js";
import { SystemRegister } from "../../../building-blocks/authentication/v2/system-register/index.js";
import { SystemRegisterDomainChecks } from "../../../domain-checks/system-register.js";

const ORG = "ttd";

export function setup() {
    requireEnv(["BASE_URL", "ENVIRONMENT"]);
    return;
}

export default async function () {
    const scopes = CreateScopeString([
        AltinnScopes.AUTHENTICATION.SYSTEMREGISTER.WRITE
    ]);

    const options = new MaskinportenTokenBuilder()
        .withScopes(scopes)
        .build();

    const tokenGenerator
        = new MaskinportenAccessTokenGenerator(options);

    // Signing the grant goes through SubtleCrypto, so the token has to be fetched
    // before the client starts asking for it.
    await tokenGenerator.ensureToken();

    const systemRegisterClient
        = new SystemRegisterClient(__ENV.BASE_URL, tokenGenerator);

    // GET /{systemId}/rights answers 403 to a Maskinporten systemregister token; it
    // wants the portal enduser scope. Registering and deleting the system still goes
    // through the Maskinporten client above, so the test needs both.
    const enduserTokenGenerator = new EnterpriseTokenGenerator(
        new EnterpriseTokenBuilder()
            .withEnvironment(__ENV.ENVIRONMENT)
            .withOrganization(ORG)
            .withScopes(CreateScopeString([AltinnScopes.PORTAL.ENDUSER]))
            .build(),
    );

    await enduserTokenGenerator.ensureToken();

    const enduserSystemRegisterClient
        = new SystemRegisterClient(__ENV.BASE_URL, enduserTokenGenerator);

    const vendorId = 313175650;
    const systemName = `K6-rights-system-${uuidv4()}`;

    const systemId = `${vendorId}_${systemName}`;

    const rights = [
        {
            "action": "read",
            "resource": [
                {
                    "id": "urn:altinn:resource",
                    "value": "authentication-e2e-test"
                }
            ]
        },
        {
            "action": "read",
            "resource": [
                {
                    "id": "urn:altinn:resource",
                    "value": "vegardtestressurs"
                }
            ]
        }
    ];

    const requestBody = new RegisterSystemRequestBuilder()
        .withName({
            "en": "K6-rights-en",
            "nb": "K6-rights-nb",
            "nn": "K6-rights-nn"
        })
        .withAllowedRedirectUrls(["https://altinn.no"])
        .withClientId([uuidv4()])
        .withVendor(`0192:${vendorId}`)
        .withId(systemId)
        .withVisibility(false)
        .withDescription({
            "en": "This is auto generated by an integration test. Some data is randomized, but some is not - like this description",
            "nb": "Integrasjonstest. Noe er randomisert her, men mye blir likt.",
            "nn": "integrasjonstest på nynorsk. Noe er randomisert her, men mye blir likt."
        })
        .withRights(rights)
        .build();

    group("System Register Rights", function () {
        group("Register a system with two rights", function () {
            // POST /vendor
            SystemRegister.VendorCreate(systemRegisterClient, requestBody);
        });

        group("An end user gets the rights of the system", function () {
            // GET /{systemId}/rights - the rights as consumers see them, not the
            // vendor view, so this one goes on the enduser token
            const registeredRights = SystemRegister.GetRights(enduserSystemRegisterClient, systemId);

            SystemRegisterDomainChecks.CheckRights(registeredRights, rights);
        });

        group("Delete the system", function () {
            const deleteResult = SystemRegister.VendorDelete(systemRegisterClient, systemId);

            SystemRegisterDomainChecks.CheckUpdateSucceeded(deleteResult, "VendorDelete");
        });
    });
}

