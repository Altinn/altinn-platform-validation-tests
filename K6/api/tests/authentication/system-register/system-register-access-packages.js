import { group } from "k6";

import { SystemRegisterClient } from "../../../../clients/authentication/v2/index.js";
import { RegisterSystemRequestBuilder } from "../../../../clients/authentication/v2/system-register.builders.js";
import { MaskinportenAccessTokenGenerator, MaskinportenTokenBuilder, uuidv4 } from "../../../../common-imports.js";
import { requireEnv } from "../../../../helpers.js";
import { AltinnScopes, CreateScopeString } from "../../../../scopes.js";
import { SystemRegister } from "../../../building-blocks/authentication/v2/system-register/index.js";
import { SystemRegisterDomainChecks } from "../../../domain-checks/system-register.js";

export function setup() {
    requireEnv(["BASE_URL"]);
    return;
}

export default async function () {
    const scopes = CreateScopeString([
        AltinnScopes.AUTHENTICATION.SYSTEMREGISTER.WRITE
    ]);

    const options = new MaskinportenTokenBuilder()
        .withScopes(scopes)
        .build();

    const tokenGenerator
        = new MaskinportenAccessTokenGenerator(options);

    // Signing the grant goes through SubtleCrypto, so the token has to be fetched
    // before the client starts asking for it.
    await tokenGenerator.ensureToken();

    const systemRegisterClient
        = new SystemRegisterClient(__ENV.BASE_URL, tokenGenerator);

    const vendorId = 313175650;
    const systemName = `K6-access-packages-system-${uuidv4()}`;

    const systemId = `${vendorId}_${systemName}`;

    const accessPackageUrns = ["urn:altinn:accesspackage:krav-og-utlegg"];

    const requestBody = new RegisterSystemRequestBuilder()
        .withName({
            "en": "K6-access-packages-en",
            "nb": "K6-access-packages-nb",
            "nn": "K6-access-packages-nn"
        })
        .withAllowedRedirectUrls(["https://altinn.no"])
        .withClientId([uuidv4()])
        .withVendor(`0192:${vendorId}`)
        .withId(systemId)
        .withDescription({
            "en": "This is auto generated by an integration test. Some data is randomized, but some is not - like this description",
            "nb": "Integrasjonstest. Noe er randomisert her, men mye blir likt.",
            "nn": "integrasjonstest på nynorsk. Noe er randomisert her, men mye blir likt."
        })
        .withAccessPackages(accessPackageUrns)
        .build();

    // A wide set, to check that an update replaces the single package the system was
    // created with rather than adding to it.
    const updatedAccessPackages = [
        { "urn": "urn:altinn:accesspackage:post-og-telekommunikasjon" },
        { "urn": "urn:altinn:accesspackage:dokumentbasert-tilsyn" },
        { "urn": "urn:altinn:accesspackage:infrastruktur" },
        { "urn": "urn:altinn:accesspackage:patent-varemerke-design" },
        { "urn": "urn:altinn:accesspackage:tilskudd-stotte-erstatning" },
        { "urn": "urn:altinn:accesspackage:mine-sider-kommune" },
        { "urn": "urn:altinn:accesspackage:politi-og-domstol" },
        { "urn": "urn:altinn:accesspackage:rapportering-statistikk" },
        { "urn": "urn:altinn:accesspackage:forskning" },
        { "urn": "urn:altinn:accesspackage:folkeregister" },
        { "urn": "urn:altinn:accesspackage:maskinporten-scopes" },
        { "urn": "urn:altinn:accesspackage:maskinlesbare-hendelser" },
        { "urn": "urn:altinn:accesspackage:maskinporten-scopes-nuf" },
    ];

    group("System Register Access Packages", function () {
        // POST /vendor - register a system with one access package
        SystemRegister.VendorCreate(systemRegisterClient, requestBody);

        // GET /{systemId}/accesspackages - as consumers see them, not the vendor view
        const registeredAccessPackages = SystemRegister.GetAccessPackages(systemRegisterClient, systemId);

        SystemRegisterDomainChecks.CheckAccessPackages(
            registeredAccessPackages,
            accessPackageUrns.map((urn) => ({ urn: urn })),
        );

        // PUT /vendor/{systemId}/accesspackages - replaces the whole set
        const updateResult = SystemRegister.VendorUpdateAccessPackages(systemRegisterClient, systemId, updatedAccessPackages);

        SystemRegisterDomainChecks.CheckUpdateSucceeded(updateResult, "VendorUpdateAccessPackages");

        const updatedRegisteredAccessPackages = SystemRegister.GetAccessPackages(systemRegisterClient, systemId);

        SystemRegisterDomainChecks.CheckAccessPackages(updatedRegisteredAccessPackages, updatedAccessPackages);

        // DELETE /vendor/{systemId} - removes the system and cleans up after the run
        const deleteResult = SystemRegister.VendorDelete(systemRegisterClient, systemId);

        SystemRegisterDomainChecks.CheckUpdateSucceeded(deleteResult, "VendorDelete");
    });
}
