import { fail, group } from "k6";

import { EnterpriseTokenBuilder, EnterpriseTokenGenerator, uuidv4 } from "../../../../common-imports.js";
import { requireEnv } from "../../../../helpers.js";
import { AltinnScopes, CreateScopeString } from "../../../../scopes.js";
import { RegisterSystemRequestBuilder, SystemRegisterBuildingBlocks, SystemRegisterClient, SystemRegisterDomainChecks } from "../../../authentication-imports.js";
import { getVendorClient, setup as commonsSetup, sweepSystems, VENDOR_ID } from "./commons.js";

const ORG = "ttd";

/**
 * What this test names its systems, which is also what its teardown sweeps up.
 * Unique per test, or two tests running at once would delete each other's systems.
 */
const SYSTEM_NAME_PREFIX = "K6-access-packages-system-";

/**
 * k6 setup stage. Fetches the vendor token, and declares the environment this test
 * needs on top of it: the rights and access packages a customer sees come back on an
 * enduser token, which is minted per environment.
 *
 * @returns {Promise<{vendorToken: string}>} The token the vendor acts with.
 */
export async function setup() {
    requireEnv(["ENVIRONMENT"]);

    return await commonsSetup();
}

export default async function (data) {
    const systemRegisterClient = getVendorClient(data.vendorToken);

    // GET /{systemId}/accesspackages wants the portal enduser scope, the same as the
    // rights endpoint. Registering, updating and deleting the system still goes
    // through the Maskinporten client above, so the test needs both.
    const enduserTokenGenerator = new EnterpriseTokenGenerator(
        new EnterpriseTokenBuilder()
            .withEnvironment(__ENV.ENVIRONMENT)
            .withOrganization(ORG)
            .withScopes(CreateScopeString([AltinnScopes.PORTAL.ENDUSER]))
            .build(),
    );

    await enduserTokenGenerator.ensureToken();

    const enduserSystemRegisterClient
        = new SystemRegisterClient(__ENV.BASE_URL, enduserTokenGenerator);

    const vendorId = VENDOR_ID;
    const systemName = `${SYSTEM_NAME_PREFIX}${uuidv4()}`;

    const systemId = `${vendorId}_${systemName}`;

    const accessPackages = [
        { "urn": "urn:altinn:accesspackage:krav-og-utlegg" },
    ];

    const requestBody = new RegisterSystemRequestBuilder()
        .withName({
            "en": "K6-access-packages-en",
            "nb": "K6-access-packages-nb",
            "nn": "K6-access-packages-nn"
        })
        .withAllowedRedirectUrls(["https://altinn.no"])
        .withClientId([uuidv4()])
        .withVendor(`0192:${vendorId}`)
        .withId(systemId)
        .withVisibility(false)
        .withDescription({
            "en": "This is auto generated by an integration test. Some data is randomized, but some is not - like this description",
            "nb": "Integrasjonstest. Noe er randomisert her, men mye blir likt.",
            "nn": "integrasjonstest på nynorsk. Noe er randomisert her, men mye blir likt."
        })
        .withAccessPackages(accessPackages.map((accessPackage) => accessPackage.urn))
        .build();

    // Disjoint from the set above, so the check also catches an update that adds to
    // the access packages instead of replacing them. The register rejects packages it
    // does not know or that are not delegable.
    const updatedAccessPackages = [
        { "urn": "urn:altinn:accesspackage:forretningsforer-eiendom" },
        { "urn": "urn:altinn:accesspackage:jordbruk" },
        { "urn": "urn:altinn:accesspackage:sjofart" },
    ];

    group("System Register Access Packages", function () {
        group("Register a system with one access package", function () {
            const createdSystemId = SystemRegisterBuildingBlocks.VendorCreate(systemRegisterClient, requestBody);

            // The groups below read, update and delete this system by id, so there is
            // nothing to assert on if the registration failed.
            if (createdSystemId === null) {
                fail("cannot continue: registering the system did not return a system id");
            }
        });

        group("An end user gets the access packages of the system", function () {
            const registeredAccessPackages = SystemRegisterBuildingBlocks.GetAccessPackagesFrontend(enduserSystemRegisterClient, systemId);

            SystemRegisterDomainChecks.CheckAccessPackages(registeredAccessPackages, accessPackages);
        });

        group("Replace the access packages on the system", function () {
            const updateResult = SystemRegisterBuildingBlocks.VendorUpdateAccessPackages(systemRegisterClient, systemId, updatedAccessPackages);

            // Reading the packages back says nothing about the update unless the
            // update itself went through.
            if (!SystemRegisterDomainChecks.CheckUpdateSucceeded(updateResult, "SystemRegisterVendorUpdateAccessPackages")) {
                fail("cannot verify the access packages: replacing them did not report success");
            }

            const updatedRegisteredAccessPackages = SystemRegisterBuildingBlocks.GetAccessPackagesFrontend(enduserSystemRegisterClient, systemId);

            SystemRegisterDomainChecks.CheckAccessPackages(updatedRegisteredAccessPackages, updatedAccessPackages);
        });

        group("Delete the system", function () {
            const deleteResult = SystemRegisterBuildingBlocks.VendorDelete(systemRegisterClient, systemId);

            SystemRegisterDomainChecks.CheckUpdateSucceeded(deleteResult, "SystemRegisterVendorDelete");
        });
    });
}

/**
 * k6 teardown stage. Removes the systems this test left in the register.
 *
 * Deleting the system is a step of the test itself, so on the way it was meant to
 * go there is nothing here to do. An iteration that gave up half way is what this
 * is for: fail() skips the delete, and the system would stay behind.
 *
 * Async, since the sweep signs its own Maskinporten grant rather than reusing the
 * token setup fetched.
 *
 * @returns {Promise<void>} Resolves once the register is swept.
 */
export async function teardown() {
    await sweepSystems(SYSTEM_NAME_PREFIX);
}

